/**
 * Type-check the built package the way a consumer resolves it: through the
 * `exports` map, against `dist`, under tsconfigs stricter than our own.
 *
 * `check-types` reads `src` with our tsconfig, which switches four strictness
 * flags off and never looks at an emitted `.d.ts`. So the two things a consumer
 * hits first are unchecked by it: whether every entrypoint in the `exports` map
 * resolves, and whether the declarations we ship are coherent. Both have broken
 * here before - twelve README specifiers and the root barrel drifting from the
 * map, each pinned after the fact by a bespoke test.
 *
 *   bun run scripts/smoke-consumer.ts
 *
 * Needs `bun run build` first; it checks `dist`, not `src`.
 *
 * NOTE: the entrypoint list is generated from `package.json` on every run rather
 * than written down, so adding an export cannot leave this check behind.
 */

import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = resolve(pkgRoot, '../..')
const tsc = join(repoRoot, 'node_modules/.bin/tsc')

/** Inside the monorepo, so `@gentleduck/auth` resolves by the normal upward walk. */
const fixture = join(pkgRoot, 'node_modules/.cache/duck-auth-smoke')

interface Permutation {
  readonly label: string
  readonly options: Record<string, unknown>
}

/**
 * Each is a setting a real consumer ships with and our own tsconfig does not.
 * `skipLibCheck: false` is the one that reads the declarations at all.
 */
const PERMUTATIONS: readonly Permutation[] = [
  { label: 'nodenext, strict', options: { module: 'NodeNext', moduleResolution: 'nodenext' } },
  { label: 'node16 resolution', options: { module: 'Node16', moduleResolution: 'node16' } },
  { label: 'bundler resolution, isolatedModules', options: { isolatedModules: true, module: 'ESNext', moduleResolution: 'bundler' } },
  { label: 'verbatimModuleSyntax', options: { module: 'NodeNext', moduleResolution: 'nodenext', verbatimModuleSyntax: true } },
  { label: 'exactOptionalPropertyTypes', options: { exactOptionalPropertyTypes: true, module: 'NodeNext', moduleResolution: 'nodenext' } },
  { label: 'noUncheckedIndexedAccess', options: { module: 'NodeNext', moduleResolution: 'nodenext', noUncheckedIndexedAccess: true } },
  { label: 'declarations read (skipLibCheck off)', options: { module: 'NodeNext', moduleResolution: 'nodenext', skipLibCheck: false } },
]

/**
 * Every leaf path in the `exports` map, with the condition chain that reached it.
 * A map is a set of promises about files, and nothing else here reads it that way:
 * TypeScript resolves a missing `types` target by falling back to a sibling
 * `.d.ts`, so a wrong or absent `types` condition type-checks clean and ships a
 * package that works only by filename coincidence.
 */
function exportTargets(exports: Record<string, unknown>): Array<{ entry: string; condition: string; target: string }> {
  const out: Array<{ entry: string; condition: string; target: string }> = []
  const walk = (entry: string, node: unknown, condition: string): void => {
    if (typeof node === 'string') {
      out.push({ condition, entry, target: node })
      return
    }
    if (node === null || typeof node !== 'object') return
    for (const [key, value] of Object.entries(node)) {
      walk(entry, value, condition ? `${condition}.${key}` : key)
    }
  }
  for (const [entry, node] of Object.entries(exports)) walk(entry, node, '')
  return out
}

function entrypoints(): string[] {
  const pkg = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8')) as {
    exports: Record<string, unknown>
  }
  return Object.keys(pkg.exports)
    .filter((name) => !name.endsWith('.json') && !name.includes('*'))
    .sort()
    .map((name) => `@gentleduck/auth${name === '.' ? '' : name.slice(1)}`)
}

function writeFixture(specs: string[], options: Record<string, unknown>): void {
  rmSync(fixture, { force: true, recursive: true })
  mkdirSync(join(fixture, 'src'), { recursive: true })
  const imports = specs.map((spec, i) => `import * as e${i} from '${spec}'`).join('\n')
  const uses = specs.map((_, i) => `e${i}`).join(', ')
  writeFileSync(
    join(fixture, 'src/index.ts'),
    `// Generated by scripts/smoke-consumer.ts. Every entrypoint in the exports map.\n${imports}\n\nexport const entrypoints = [${uses}]\n`,
  )
  writeFileSync(
    join(fixture, 'tsconfig.json'),
    `${JSON.stringify(
      {
        compilerOptions: { noEmit: true, skipLibCheck: true, strict: true, target: 'ESNext', types: ['node'], ...options },
        include: ['src'],
      },
      null,
      2,
    )}\n`,
  )
}

/**
 * Our emitted declarations, or the generated fixture itself. A peer dependency's
 * own declarations are neither: `skipLibCheck: false` surfaces 65 from
 * drizzle-orm alone - including a `TS2307` for the optional `gel` driver - and
 * none of them say anything about this package, so a check that counted every
 * line would never be green.
 */
function isOurs(line: string): boolean {
  const file = line.split('(')[0] ?? ''
  return /(^|\/)dist\//.test(file) || file.includes('duck-auth-smoke')
}

const specs = entrypoints()
if (!existsSync(join(pkgRoot, 'dist/index.d.ts'))) {
  console.error('dist/index.d.ts is missing - run `bun run build` first.')
  process.exit(2)
}

console.log(`${specs.length} entrypoints from the exports map, against dist/\n`)
let failed = 0

const pkgJson = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8')) as {
  exports: Record<string, unknown>
}
const targets = exportTargets(pkgJson.exports)
const absent = targets.filter(({ target }) => !existsSync(join(pkgRoot, target)))
if (absent.length > 0) {
  failed++
  console.log(`  FAIL  every exports target exists (${absent.length} of ${targets.length} missing)`)
  for (const { condition, entry, target } of absent.slice(0, 12)) {
    console.log(`          ${entry} [${condition}] -> ${target}`)
  }
} else {
  console.log(`  ok    every exports target exists (${targets.length} files)`)
}

/** A consumer that resolves by `require` needs its own `types`, and so does `import`. */
const untyped = Object.entries(pkgJson.exports)
  .filter(([name]) => !name.endsWith('.json') && !name.includes('*'))
  .flatMap(([entry, node]) =>
    ['import', 'require']
      .filter((cond) => {
        const branch = (node as Record<string, unknown>)?.[cond]
        return branch !== undefined && (typeof branch !== 'object' || branch === null || !('types' in branch))
      })
      .map((cond) => `${entry} [${cond}]`),
  )
if (untyped.length > 0) {
  failed++
  console.log(`  FAIL  every exports condition declares types (${untyped.length} without)`)
  for (const name of untyped.slice(0, 12)) console.log(`          ${name}`)
} else {
  console.log('  ok    every exports condition declares types')
}

for (const { label, options } of PERMUTATIONS) {
  writeFixture(specs, options)
  const out = spawnSync(tsc, ['-p', join(fixture, 'tsconfig.json'), '--pretty', 'false'], {
    cwd: pkgRoot,
    encoding: 'utf8',
  })
  const lines = `${out.stdout ?? ''}${out.stderr ?? ''}`.split('\n').filter((l) => l.includes('error TS'))
  const bad = lines.filter(isOurs)
  if (bad.length === 0) {
    const noise = lines.length > 0 ? ` (${lines.length} in peer deps, ignored)` : ''
    console.log(`  ok    ${label}${noise}`)
    continue
  }
  failed++
  console.log(`  FAIL  ${label}`)
  for (const line of bad.slice(0, 12)) console.log(`          ${line}`)
}

rmSync(fixture, { force: true, recursive: true })
if (failed > 0) {
  console.error(`\n${failed} check(s) failed.`)
  process.exit(1)
}
console.log(`\nAll clean: ${PERMUTATIONS.length} consumer configurations, ${targets.length} exports targets.`)
